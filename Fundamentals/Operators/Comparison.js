// 1. Equality Operator (==)

// Illustration of (==) operator
let x = 5;
let y = '5';

// Checking of operands
console.log(x == 5);
console.log(y == 5);        
console.log(x == y);

console.log();

// Check against special values
console.log(NaN == NaN);
console.log(0 == false);   
console.log(0 == null);
