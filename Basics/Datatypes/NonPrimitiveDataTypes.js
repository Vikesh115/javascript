/* 
    (Non-primitive) or (Mutable) data types in javascript
 */
/*
    Array, Object etc.,
*/
/*
    Multiple values assigned to a variable.
*/
/*  Non-primitive values are mutable, meaning their values
    can be changed after they are created.
*/
/*
    When an operation appears to modify a non-primitive value, 
    it actually takes referance of value.
*/
/*
    These data types do have methods or properties.
*/

let info = { name: "vikesh", age: 22, gender: "male" }
console.log(info);
console.log(info.name);
console.log(typeof info);

let arr = [{ myName: "vik" }, { name: "raut" }]
console.log(arr);
console.log(typeof arr);